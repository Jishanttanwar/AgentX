"""
Pydantic schemas for Agent 4 (Analyst) and Agent 5 (Fact Checker).
Enforces structured extraction of cross-source patterns, empirical trends,
atomic factual claims, and strict evidence verification matrices.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
import uuid
from pydantic import BaseModel, Field


class InsightCategory(str, Enum):
    """Categorization of analytical insights discovered across research findings."""
    TREND = "trend"
    PATTERN = "pattern"
    STATISTIC = "statistic"
    CONTRADICTION = "contradiction"
    STRATEGIC = "strategic"


class AnalyticalInsight(BaseModel):
    """
    An insight generated by the Analyst Agent synthesizing findings across tasks.
    Enforces clear separation between empirical evidence and interpretive analysis.
    """

    insight_id: str = Field(
        default_factory=lambda: f"ins_{uuid.uuid4().hex[:8]}",
        description="Unique identifier for the analytical insight",
    )
    title: str = Field(..., description="Concise summary title of the insight")
    category: InsightCategory = Field(
        default=InsightCategory.PATTERN,
        description="Type of analytical synthesis",
    )
    empirical_evidence: str = Field(
        ...,
        description="Strictly factual data points, metrics, and observations from sources",
    )
    strategic_interpretation: str = Field(
        ...,
        description="Analyst's forward-looking synthesis or contextual interpretation",
    )
    related_task_ids: List[str] = Field(
        default_factory=list,
        description="Tasks contributing findings to this insight",
    )
    supporting_finding_ids: List[str] = Field(
        default_factory=list,
        description="IDs of specific ResearchFinding items backing this insight",
    )
    confidence_score: float = Field(
        default=0.9,
        ge=0.0,
        le=1.0,
        description="Confidence level in the validity of the synthesis",
    )
