"""
Pydantic schemas for the Research Plan and Task decomposition.
Ensures strict validation, type safety, and rich structure for multi-agent workflows.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field, computed_field


class ResearchDepth(str, Enum):
    """Depth configuration for research planning."""
    QUICK = "quick"              # 2-3 focused tasks
    STANDARD = "standard"        # 4-6 balanced tasks
    COMPREHENSIVE = "comprehensive"  # 7-10 deep multi-angle tasks


class ResearchTaskType(str, Enum):
    """Domain category for a research subtask."""
    GENERAL = "general"
    MARKET = "market"
    TECHNICAL = "technical"
    REGULATORY = "regulatory"
    ACADEMIC = "academic"
    CLINICAL_OR_EMPIRICAL = "clinical_or_empirical"
    COMPARATIVE = "comparative"


class AgentType(str, Enum):
    """Specialized agent types in AgentX."""
    ORCHESTRATOR = "orchestrator"
    PLANNER = "planner"
    RESEARCHER = "researcher"
    ANALYST = "analyst"
    FACT_CHECKER = "fact_checker"
    WRITER = "writer"
    REVIEWER = "reviewer"


class ResearchTask(BaseModel):
    """A granular, non-overlapping research task executed by Researcher agents."""

    task_id: str = Field(
        ...,
        description="Unique identifier for the task, e.g., 'task_1', 'task_2'",
    )
    title: str = Field(
        ...,
        description="Concise, descriptive title for the task (e.g. 'Current AI applications in healthcare')",
    )
    description: str = Field(
        ...,
        description="Specific guidance on what facts, data, trends, or evidence to find",
    )
    research_type: ResearchTaskType = Field(
        default=ResearchTaskType.GENERAL,
        description="Domain category for targeted search strategy",
    )
    search_queries: List[str] = Field(
        default_factory=list,
        description="2-3 targeted web search queries tailored for search engines",
    )
    assigned_agents: List[AgentType] = Field(
        default_factory=lambda: [AgentType.RESEARCHER],
        description="Agents needed to process this specific task",
    )
    priority: int = Field(
        default=1,
        ge=1,
        le=3,
        description="Priority ranking: 1 (critical path), 2 (standard), 3 (supplementary)",
    )


class ResearchPlan(BaseModel):
    """Complete structured research plan generated by the Planner Agent."""

    topic: str = Field(
        ...,
        description="The overarching research topic or subject area",
    )
    objective: str = Field(
        ...,
        description="Clear statement of the primary research goal and questions to answer",
    )
    research_depth: ResearchDepth = Field(
        default=ResearchDepth.STANDARD,
        description="Configured depth level for the research plan",
    )
    research_tasks: List[ResearchTask] = Field(
        ...,
        min_length=1,
        description="List of structured research subtasks to be executed by agents",
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of plan creation",
    )

    @computed_field
    @property
    def task_titles(self) -> List[str]:
        """Convenience property returning task titles list matching prompt example."""
        return [task.title for task in self.research_tasks]


class PlanGenerationRequest(BaseModel):
    """User input payload for generating a research plan."""

    query: str = Field(
        ...,
        min_length=3,
        max_length=2000,
        description="User's research query or problem statement",
        examples=["Research the future of artificial intelligence in healthcare."],
    )
    depth: ResearchDepth = Field(
        default=ResearchDepth.STANDARD,
        description="Depth of research: quick, standard, or comprehensive",
    )
    additional_context: Optional[str] = Field(
        default=None,
        max_length=5000,
        description="Optional supplementary background or domain constraints",
    )


class PlanGenerationResponse(BaseModel):
    """API response envelope containing the generated research plan."""

    success: bool = True
    plan: ResearchPlan
    model_used: str
    execution_time_ms: float
